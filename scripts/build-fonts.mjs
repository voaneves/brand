export async function buildFonts() {
  const subsetText = buildSubsetText();
  const sizes = {};

  for (const job of FONT_JOBS) {
    const input = await fs.readFile(job.src);
    const output = await subsetFont(input, subsetText, {
      targetFormat: 'woff2',
      variationAxes: job.variationAxes,
      keepFeatures: ['kern', 'liga', 'locl', 'mark', 'mkmk'],
      noHinting: true,
    });
    await fs.writeFile(job.dest, output);
    sizes[path.basename(job.dest)] = output.length;
  }

  for (const [familyDir, destName] of OFL_FILES) {
    await fs.copyFile(
      path.join(SOURCE_DIR, familyDir, 'OFL.txt'),
      path.join(FONTS_DIR, destName),
    );
  }

  await fs.mkdir(DIST_CSS_DIR, { recursive: true });
  await fs.writeFile(path.join(DIST_CSS_DIR, 'fonts.css'), FONTS_CSS, 'utf8');

  return sizes;
}

const isCli =
  process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isCli) {
  const sizes = await buildFonts();
  for (const [name, bytes] of Object.entries(sizes)) {
    console.log(`${name}: ${bytes} bytes (${(bytes / 1024).toFixed(1)} KB)`);
  }
}
