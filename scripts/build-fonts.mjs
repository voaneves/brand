function buildSubsetText() {
  const ranges = [
    [0x0020, 0x007e],
    [0x0152, 0x0153],
    [0x2013, 0x2014],
    [0x2018, 0x201d],
    [0x2190, 0x2193],
  ];
  const singles = [
    0x00a0, 0x00a3, 0x00a7, 0x00a9, 0x00aa, 0x00ab, 0x00ae, 0x00b0, 0x00b1, 0x00b7, 0x00ba, 0x00bb, 0x00d7,
    0x2022, 0x2026, 0x2082, 0x20ac, 0x2122, 0x2212,
  ];
  const letters = 'ÀÁÂÃÄÇÈÉÊÍÑÒÓÔÕÖÚÛÜàáâãäçèéêíñòóôõöúûü';
  let out = letters;
  for (const [start, end] of ranges) {
    for (let cp = start; cp <= end; cp += 1) {
      out += String.fromCodePoint(cp);
    }
  }
  for (const cp of singles) {
    out += String.fromCodePoint(cp);
  }
  return out;
}

