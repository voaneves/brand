// Builds dist/tailwind/theme.css, a Tailwind v4 theme that maps utilities to the --vn-* custom properties.
// Usage in an app:
//   @import "tailwindcss";
//   @import "@voaneves/brand/css/all.css";
//   @import "@voaneves/brand/tailwind/theme.css";
// `@theme inline` keeps utilities pointing at var(--vn-*), so light/dark (light-dark()) keeps working.
// Run after build:tokens: npm run build:tailwind
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'tailwind');

const COLORS = [
  'ink', 'ink-soft', 'cream', 'cream-soft', 'signal', 'signal-2', 'signal-ink',
  'surface', 'surface-soft', 'surface-raised', 'surface-inverse', 'surface-signal',
  'text', 'text-muted', 'text-on-inverse', 'text-muted-on-inverse', 'text-on-signal',
  'line', 'line-strong', 'line-on-dark', 'focus', 'focus-on-signal',
  'viz-1', 'viz-2', 'viz-3', 'viz-grid',
  'viz-seq-1', 'viz-seq-2', 'viz-seq-3', 'viz-seq-4', 'viz-seq-5',
  'viz-div-neg-2', 'viz-div-neg-1', 'viz-div-mid', 'viz-div-pos-1', 'viz-div-pos-2',
];
const SHADOWS = ['pop', 'lift', 'media', 'drawer', 'signal', 'dot'];
const RADII = ['xs', 'sm', 'md', 'lg', 'xl', '2xl', 'pill', 'round'];
const EASES = ['out', 'spring', 'in-out'];
const SPACES = ['beat', 'breath', 'pause'];
const TYPES = ['hero', 'display', 'numeral', 'h1', 'h2', 'h3', 'h4', 'quote', 'lead', 'body', 'body-strong', 'body-sm', 'caption', 'label', 'tag', 'micro', 'wordmark', 'price', 'code'];

export async function buildTailwind() {
  const tokensCss = await fs.readFile(path.join(ROOT, 'dist', 'css', 'tokens.css'), 'utf8');
  const has = (name) => new RegExp(`--vn-${name}:`).test(tokensCss);
  const lines = [];
  const add = (prop, name) => {
    if (!has(name)) throw new Error(`--vn-${name} is missing from dist/css/tokens.css`);
    lines.push(`  --${prop}: var(--vn-${name});`);
  };

  // Drop Tailwind's default palette so only brand colors exist.
  lines.push('  --color-*: initial;');
  lines.push('  --color-transparent: transparent;');
  lines.push('  --color-current: currentColor;');
  for (const c of COLORS) add(`color-${c}`, c);
  lines.push('');
  for (const f of ['display', 'text', 'mono']) add(`font-${f}`, `font-${f}`);
  lines.push('');
  for (const r of RADII) add(`radius-${r}`, `radius-${r}`);
  lines.push('');
  for (const s of SHADOWS) add(`shadow-${s}`, `shadow-${s}`);
  lines.push('');
  for (const e of EASES) add(`ease-${e}`, `ease-${e}`);
  lines.push('');
  for (const s of SPACES) add(`spacing-${s}`, `space-${s}`);
  lines.push('');
  for (const t of TYPES) {
    add(`text-${t}`, `type-${t}-size`);
    add(`text-${t}--line-height`, `type-${t}-line-height`);
    add(`text-${t}--letter-spacing`, `type-${t}-tracking`);
    add(`text-${t}--font-weight`, `type-${t}-weight`);
  }

  const css = `/* Generated by scripts/build-tailwind.mjs from dist/css/tokens.css. Do not edit. */
/* Requires Tailwind CSS v4 and @voaneves/brand/css/tokens.css (or all.css). */
@theme inline {
${lines.join('\n')}
}
`;
  await fs.mkdir(OUT, { recursive: true });
  await fs.writeFile(path.join(OUT, 'theme.css'), css);
  return css;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildTailwind();
  console.log('Wrote dist/tailwind/theme.css');
}
